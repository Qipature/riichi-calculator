function exampleTileIndex(code){
 const digit=Number(code[0])-1, suit=code[1];
 return suit==='z'?27+digit:({m:0,p:9,s:18}[suit])+digit;
}
function tileFace(i){
 return '<svg class="tile-face" viewBox="0 0 300 400" aria-hidden="true" focusable="false"><use href="./assets/tiles.svg#tile-'+i+'"></use></svg>';
}
function exampleTile(code,kind=''){
 const i=exampleTileIndex(code);
 return '<span class="tile art-tile '+kind+'" role="img" aria-label="'+(kind==='winning'?'和牌张 ':'')+TILE_LABELS[i]+'" title="'+TILE_LABELS[i]+'">'+(kind==='face-down'?'<span class="tile-back"></span>':tileFace(i))+'</span>';
}
function splitExample(id){
 const [shape,win,,state={}]=YAKU_EXAMPLES[id],fixed=state.melds||[];
 const groups=shape.split(' ').map(g=>[...g.slice(0,-1)].map(d=>d+g.at(-1)));
 // The winning tile must come from the concealed portion, never a declared meld.
 let removed=false;
 for(let g=groups.length-1;g>=0;g--){
  if(fixed.some(m=>m.group===g))continue;
  const at=groups[g].lastIndexOf(win);
  if(at>=0){groups[g].splice(at,1);removed=true;break;}
 }
 if(!removed)throw Error('和牌张不在未副露手牌中：'+id);
 return {groups,win,fixed,focus:state.focus||[]};
}
function exampleHTML(id){
 const [, ,note]=YAKU_EXAMPLES[id],{groups,win,fixed,focus}=splitExample(id);
 const groupHTML=(codes,index,meld)=>{
  const tiles=codes.map((code,j)=>exampleTile(code,meld?.type==='ankan'&&(j===0||j===codes.length-1)?'face-down':meld&&meld.type!=='ankan'&&j===0?'sideways':'')).join('');
  const label=meld?({chi:'吃',pon:'碰',minkan:'明杠',ankan:'暗杠'}[meld.type]):'';
  return '<div class="example-group'+(focus.includes(index)?' focus-group':'')+'"><div class="group-tiles">'+tiles+'</div>'+(label?'<small>'+label+'</small>':'')+'</div>';
 };
 const closed=groups.map((codes,i)=>fixed.some(m=>m.group===i)?'':groupHTML(codes,i)).join('');
 const called=fixed.map(m=>groupHTML(groups[m.group],m.group,m)).join('');
 return '<div class="yaku-example"><div class="example-caption">和牌示例 <span>浅绿底为关键牌组；金框为最后和牌张</span></div><div class="example-layout"><div class="example-main"><div class="zone-title">手里的牌（未副露）</div><div class="example-hand">'+closed+'</div>'+(called?'<div class="fixed-zone"><div class="zone-title">摆出的牌组 <span>吃、碰、明杠是副露；暗杠仍门清</span></div><div class="example-hand">'+called+'</div></div>':'')+'</div><div class="winning-zone"><div class="zone-title">和牌张</div>'+exampleTile(win,'winning')+'</div></div><p><b>成立条件：</b>'+note+'</p></div>';
}
function yakuCatalogue(){
 const normal=Y.concat(HONOR_YAKU).map(y=>({id:y[0],name:y[1],h:y[2],oh:y[3],desc:y[5]||y[4],kind:'normal',rank:y[2]}));
 const yakuman=Z.map(z=>({id:z[0],name:z[1],h:13,desc:z[2],kind:'yakuman',oh:-1,rank:100}));
 const ancient=ANCIENT_YAKU.map(a=>({id:a[0],name:a[1],desc:a[2],kind:'ancient',...a[3]}));
 return normal.concat(yakuman,ancient).sort((a,b)=>a.rank-b.rank);
}
