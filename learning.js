function renderGlossary(){
 const query=v('termSearch').trim().toLowerCase(),category=v('termCategory');let count=0;
 $('termCards').innerHTML=GLOSSARY.filter(g=>category==='all'||category===g[0]).map(([name,terms])=>{
  const selected=terms.filter(t=>(t[0]+t[1]).toLowerCase().includes(query));count+=selected.length;
  return selected.length?'<section class="term-section"><h3>'+name+'</h3><div class="term-grid">'+selected.map(t=>'<article class="term-card"><h4>'+t[0]+'</h4><p>'+t[1]+'</p></article>').join('')+'</div></section>':'';
 }).join('');
 $('termCount').textContent='找到 '+count+' 条术语解释';
 if(!count)$('termCards').innerHTML='<p class="sm">没有找到对应术语，试试别名或清空筛选。</p>';
}
function updateHonorLabels(){
 document.querySelectorAll('.honorCb').forEach(input=>{
  const name=input.value,dragon={white:'白',green:'发',redDragon:'中'}[name];
  const seat=v('seatWind')===name,round=v('roundWind')===name;
  const label=dragon?'三元牌 · '+dragon+' · 1番':WIND[name]+' · '+(seat&&round?'连风（自风＋场风）· 2番':seat?'自风 · 1番':round?'场风 · 1番':'客风 · 0番');
  // Preserve checkbox and its listeners/selection as wind settings change.
  if(!input.nextElementSibling){const span=document.createElement('span');input.after(span);while(span.nextSibling)span.nextSibling.remove();}
  input.nextElementSibling.textContent=label+'（刻子/杠）';
 });
}
